-- ─── REPORTFLOW SUPABASE DATABASE SCHEMA ──────────────────────────────────
-- Run this script in the Supabase Dashboard -> SQL Editor

-- 1. Create Members Table
CREATE TABLE IF NOT EXISTS public.members (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    role TEXT NOT NULL DEFAULT 'Staff Member',
    department TEXT NOT NULL DEFAULT 'Engineering',
    compliance INTEGER NOT NULL DEFAULT 95,
    initials TEXT NOT NULL DEFAULT 'US',
    color TEXT NOT NULL DEFAULT '#005030',
    is_admin BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Reports Table (with attachments JSONB support)
CREATE TABLE IF NOT EXISTS public.reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    author TEXT NOT NULL,
    department TEXT NOT NULL,
    type TEXT NOT NULL, -- 'Daily', 'Weekly', 'Monthly', 'Quarterly', 'Yearly'
    status TEXT NOT NULL DEFAULT 'Draft', -- 'Draft', 'Submitted', 'Approved', 'Flagged'
    summary TEXT,
    feedback TEXT,
    attachments JSONB DEFAULT '[]'::jsonb,
    gve_daily_data JSONB,
    gve_weekly_data JSONB,
    gve_quarterly_data JSONB,
    submitted_at TIMESTAMPTZ DEFAULT NOW(),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Migration for existing databases:
ALTER TABLE public.reports ADD COLUMN IF NOT EXISTS attachments JSONB DEFAULT '[]'::jsonb;

-- 3. Create Deadlines Table
CREATE TABLE IF NOT EXISTS public.deadlines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    department TEXT NOT NULL DEFAULT 'All Departments',
    due_date DATE NOT NULL,
    description TEXT,
    priority TEXT DEFAULT 'Medium',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Enable Row Level Security (RLS)
ALTER TABLE public.members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reports ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.deadlines ENABLE ROW LEVEL SECURITY;

-- 5. Create Public Access Policies (Allow authenticated & anon read/write for app client)
CREATE POLICY "Allow public read access to members" ON public.members FOR SELECT USING (true);
CREATE POLICY "Allow public insert/update to members" ON public.members FOR ALL USING (true);

CREATE POLICY "Allow public read access to reports" ON public.reports FOR SELECT USING (true);
CREATE POLICY "Allow public insert/update/delete to reports" ON public.reports FOR ALL USING (true);

CREATE POLICY "Allow public read access to deadlines" ON public.deadlines FOR SELECT USING (true);
CREATE POLICY "Allow public insert/update/delete to deadlines" ON public.deadlines FOR ALL USING (true);

-- 6. Enable Realtime Replication (so changes appear instantly without refreshing)
ALTER PUBLICATION supabase_realtime ADD TABLE public.reports;
ALTER PUBLICATION supabase_realtime ADD TABLE public.members;
ALTER PUBLICATION supabase_realtime ADD TABLE public.deadlines;

-- 7. Supabase Storage Bucket for Report Attachments
-- To enable remote Supabase Storage for report photos:
-- In Supabase Dashboard -> Storage -> Create New Bucket -> "report-attachments" (Set to Public)
-- Or run:
INSERT INTO storage.buckets (id, name, public)
VALUES ('report-attachments', 'report-attachments', true)
ON CONFLICT (id) DO NOTHING;

CREATE POLICY "Allow public uploads to report-attachments bucket"
ON storage.objects FOR INSERT
WITH CHECK (bucket_id = 'report-attachments');

CREATE POLICY "Allow public reads from report-attachments bucket"
ON storage.objects FOR SELECT
USING (bucket_id = 'report-attachments');

